/**
 * OpenAPI 3.x document builder from `@verimaya/shared` `apiContract`.
 * Shared by the CLI (`generate-openapi.js`) and the vitest drift guard.
 *
 * AUDIT-F09-01: hand-maintained openapi.yaml is retired; this is the sole source.
 *
 * Always load shared from `packages/shared/dist` — vitest/Vite enables the
 * `development` export condition which would resolve to `src/*.ts` and break
 * plain Node `require` (missing `.js` siblings for TypeScript sources).
 */

const fs = require('node:fs');
const path = require('node:path');
const { zodToJsonSchema } = require('zod-to-json-schema');
const YAML = require('yaml');

function loadApiContract() {
	// Prefer the workspace symlink (stable regardless of export conditions).
	// Vitest enables the `development` condition which would resolve
	// `require('@verimaya/shared')` to `src/index.ts` and break plain Node.
	const candidates = [
		path.join(__dirname, '..', 'node_modules', '@verimaya', 'shared', 'dist', 'index.js'),
		path.join(__dirname, '..', '..', '..', 'packages', 'shared', 'dist', 'index.js')
	];
	const distEntry = candidates.find((p) => fs.existsSync(p));
	if (!distEntry) {
		throw new Error(
			`@verimaya/shared dist missing (tried: ${candidates.join(', ')}). Run: pnpm --filter @verimaya/shared build`
		);
	}
	const shared = require(distEntry);
	if (!shared.apiContract || typeof shared.apiContract !== 'object') {
		throw new Error('@verimaya/shared dist does not export apiContract');
	}
	return shared.apiContract;
}
